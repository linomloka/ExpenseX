export const translations = { EN: {}, SW: swahili }

export function translate(language, text) {
  return language === 'SW' ? swahili[text] || text : text
}

const TranslationContext = createContext((text) => text)

export function TranslationProvider({ language, children }) {
  return createElement(TranslationContext.Provider, { value: (text) => translate(language, text) }, children)
}

export function useTranslate() {
  return useContext(TranslationContext)
}
